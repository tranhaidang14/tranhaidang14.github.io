const originals = new WeakMap();
let originalDocumentTitle = null;

function remember(element, key, value) {
  if (value === undefined) return;
  const store = originals.get(element) || {};
  if (!(key in store)) store[key] = value;
  originals.set(element, store);
}

function captureOriginals(root) {
  originalDocumentTitle = document.title;

  root.querySelectorAll("[data-i18n]").forEach((element) => {
    remember(element, "html", element.innerHTML);
  });

  root.querySelectorAll("[data-i18n-html]").forEach((element) => {
    remember(element, "i18nHtml", element.innerHTML);
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    remember(element, "placeholder", element.getAttribute("placeholder"));
  });

  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    remember(element, "ariaLabel", element.getAttribute("aria-label"));
  });

  root.querySelectorAll("[data-i18n-title-attr]").forEach((element) => {
    remember(element, "title", element.getAttribute("title"));
  });

  root.querySelectorAll("meta[data-i18n-meta]").forEach((element) => {
    remember(element, "content", element.getAttribute("content"));
  });
}

export function getLang() {
  return "vi";
}

export function t(key, vars) {
  let value = STRINGS[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(replacement));
    }
  }
  return value;
}

export function apply(root = document) {
  document.documentElement.lang = "vi";

  root.querySelectorAll("[data-i18n]").forEach((element) => {
    const original = originals.get(element)?.html;
    element.innerHTML = original !== undefined ? original : t(element.dataset.i18n);
  });

  root.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const original = originals.get(element)?.i18nHtml;
    element.innerHTML = original !== undefined ? original : t(element.dataset.i18nHtml);
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const original = originals.get(element)?.placeholder;
    element.setAttribute(
      "placeholder",
      original != null ? original : t(element.dataset.i18nPlaceholder)
    );
  });

  root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
    const original = originals.get(element)?.ariaLabel;
    element.setAttribute(
      "aria-label",
      original != null ? original : t(element.dataset.i18nAriaLabel)
    );
  });

  root.querySelectorAll("[data-i18n-title-attr]").forEach((element) => {
    const original = originals.get(element)?.title;
    element.setAttribute(
      "title",
      original != null ? original : t(element.dataset.i18nTitleAttr)
    );
  });

  root.querySelectorAll("meta[data-i18n-meta]").forEach((element) => {
    const original = originals.get(element)?.content;
    element.setAttribute(
      "content",
      original != null ? original : t(element.dataset.i18nMeta)
    );
  });

  const titleKey = document.body?.dataset.i18nTitle;
  if (titleKey) {
    document.title = originalDocumentTitle ?? t(titleKey);
  }
}

export function onLanguageChange() {
  /* The interface is Vietnamese only; this is kept for callers that re-render dates. */
}

export function initI18n() {
  try {
    window.localStorage.removeItem("encyclopedia-lang");
  } catch {
    /* Nothing to clean up. */
  }
  captureOriginals(document);
  apply();
}
