#!/usr/bin/env node
/**
 * bundle.mjs — turn the ES modules in assets/js into small classic scripts.
 *
 * The site can then be opened straight from disk as well as over HTTP, without
 * relying on a server to resolve module imports. The source files stay the
 * files you edit; `tools/build.mjs` regenerates `assets/js/app/` from them.
 */
import { readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const JS_DIR = path.join(ROOT, "assets", "js");
const OUT_DIR = path.join(JS_DIR, "app");

function resolveId(fromId, specifier) {
  if (!specifier.startsWith(".")) return specifier;
  return path.posix.normalize(path.posix.join(path.posix.dirname(fromId), specifier));
}

function transform(source, id) {
  const deps = new Set();
  let code = source;

  code = code.replace(
    /import\s*\{([\s\S]*?)\}\s*from\s*["']([^"']+)["'];?/g,
    (_, bindings, specifier) => {
      const dep = resolveId(id, specifier);
      deps.add(dep);
      const names = bindings
        .split(",")
        .map((piece) => piece.trim())
        .filter(Boolean)
        .map((piece) => {
          const [name, alias] = piece.split(/\s+as\s+/);
          return alias ? `${name}: ${alias}` : name;
        })
        .join(", ");
      return `const { ${names} } = __require(${JSON.stringify(dep)});`;
    }
  );

  const exported = [];

  code = code.replace(
    /export\s+(async\s+function|function|const|let|var|class)\s+([A-Za-z_$][\w$]*)/g,
    (_, kind, name) => {
      exported.push(`${name}: ${name}`);
      return `${kind} ${name}`;
    }
  );

  code = code.replace(/export\s*\{([\s\S]*?)\};?/g, (_, bindings) => {
    for (const piece of bindings.split(",")) {
      const [name, alias] = piece.trim().split(/\s+as\s+/);
      if (!name) continue;
      exported.push(`${alias || name}: ${name}`);
    }
    return "";
  });

  if (exported.length) {
    code += `\n${exported
      .map((entry) => {
        const [publicName, localName] = entry.split(": ");
        return `__exports[${JSON.stringify(publicName)}] = ${localName};`;
      })
      .join("\n")}\n`;
  }

  return { code, deps };
}

async function readModule(id, modules) {
  if (modules.has(id)) return;
  const source = await readFile(path.join(JS_DIR, id), "utf8");
  const { code, deps } = transform(source, id);
  modules.set(id, code);
  for (const dep of deps) await readModule(dep, modules);
}

export async function bundleScripts(entries) {
  await mkdir(OUT_DIR, { recursive: true });

  for (const { name, modules: entryModules } of entries) {
    const modules = new Map();
    for (const entry of entryModules) await readModule(entry, modules);

    const definitions = [...modules.entries()]
      .map(
        ([id, code]) => `    ${JSON.stringify(id)}: function (__exports, __require) {\n${code
          .split("\n")
          .map((line) => `      ${line}`)
          .join("\n")}\n    }`
      )
      .join(",\n");

    const bundle = `/* Generated by tools/bundle.mjs — edit assets/js/*.js instead. */
(function () {
  "use strict";
  const __defs = {
${definitions}
  };
  const __cache = {};
  function __require(id) {
    if (__cache[id]) return __cache[id].exports;
    const definition = __defs[id];
    if (!definition) throw new Error("Module not found: " + id);
    const module = { exports: {} };
    __cache[id] = module;
    definition(module.exports, __require);
    return module.exports;
  }
${entryModules.map((id) => `  __require(${JSON.stringify(id)});`).join("\n")}
})();
`;

    await writeFile(path.join(OUT_DIR, `${name}.js`), bundle);
  }
}

export const BUNDLE_ENTRIES = [
  { name: "home", modules: ["core.js", "home.js"] },
  { name: "writing", modules: ["core.js", "writing.js"] },
  { name: "library", modules: ["core.js", "library.js"] },
  { name: "article", modules: ["core.js", "article.js"] },
  { name: "about", modules: ["core.js"] },
  { name: "404", modules: ["core.js"] },
];
